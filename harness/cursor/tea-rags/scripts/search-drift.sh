#!/usr/bin/env bash
# Stateful search-drift hook (bd tea-rags-mcp-nknkg.2; the Serena
# PreToolUseRemindAboutSymbolicToolsHook pattern). Agents drift from tea-rags to
# text search and raw reads as a session grows; a counter notices the streak and
# DENIES one call with a reason naming the tea-rags call to use.
#
# Per-session counters, no tea-rags call in between:
#   3 consecutive concept searches done by text search (Grep tool; shell grep /
#     egrep / fgrep / rg / ag / ack / git grep starting a command) — an
#     alternation `a|b` / `a\|b` / two -e patterns. A single literal (identifier,
#     constant, phrase), any -F search and `<cmd> | grep` over output are neutral:
#     core routes literal and occurrence searches to the text-search tool, OR
#   3 consecutive reads of indexed source code (Read tool; shell cat / sed / head
#     / tail / less / more — membership by `tea-rags project indexed`; a file
#     outside the index is neutral), OR
#   4 of them mixed.
# Never counted (bd tea-rags-mcp-nxg76): a read of, or a search scoped to,
# config / DSL / routes / initializers / migrations / specs / tests / fixtures /
# data files (`standard_zone`) — core routes those to the standard tools.
# → DENY once, reset the counters, at most one deny per 120 s. Drift is a
# within-turn phenomenon: a new user prompt (UserPromptSubmit on Claude / Codex,
# beforeSubmitPrompt on Cursor — this script is wired there too) resets the
# counters and keeps the deny timestamp, so the cooldown survives turns. A successful
# tea-rags MCP call resets the counters. Edits, writes and every other tool are
# neutral: neither counted nor reset.
#
# One script, three harnesses (`--harness claude|codex|cursor`; Codex and Cursor
# ship this file byte-identical, generated by scripts/gen-harness-*.ts):
#   claude — PreToolUse(Read|Grep|Bash) counts, deny = permissionDecision JSON;
#            PostToolUse(tea-rags MCP) resets.
#   codex  — PreToolUse(shell) counts, deny = exit 2 + reason on stderr;
#            PostToolUse(tea-rags MCP) resets.
#   cursor — preToolUse(Shell|Read|Grep) counts, deny = {"permission":"deny",…};
#            afterMCPExecution(server tea-rags) resets.
#
# State: one line "<searches> <reads> <total> <last deny epoch>" per harness and
# session id in $TEA_RAGS_HOOK_STATE_DIR (default: the harness plugin-data dir,
# else $TMPDIR/tea-rags-hooks). Clock: $TEA_RAGS_HOOK_NOW, else `date +%s`.
#
# Fail open, always: no jq, unparsable input, no session id, unwritable state,
# a CLI error — the tool call proceeds. Cursor blocks a permission hook whose
# stdout is not schema-valid JSON, so every Cursor exit prints JSON. Exit 0
# except the Codex deny (exit 2).

HARNESS=claude
while [ $# -gt 0 ]; do
  case "$1" in
    --harness) HARNESS="${2:-claude}"; shift 2 || shift ;;
    *) shift ;;
  esac
done

allow() {
  [ "$HARNESS" = cursor ] && echo '{"permission":"allow"}'
  exit 0
}
pass() {
  [ "$HARNESS" = cursor ] && echo '{}'
  exit 0
}
command -v jq >/dev/null 2>&1 || allow
INPUT=$(cat)
field() { printf '%s' "$INPUT" | jq -r "$1 // empty" 2>/dev/null; }

EVENT=$(field '.hook_event_name' | tr '[:upper:]' '[:lower:]')
[ -n "$EVENT" ] || allow
SID=$(field '.session_id // .conversation_id' | tr -c 'A-Za-z0-9_.-' '_')
[ -n "$SID" ] || allow
STATE_DIR="${TEA_RAGS_HOOK_STATE_DIR:-${CLAUDE_PLUGIN_DATA:-${PLUGIN_DATA:-${TMPDIR:-/tmp}/tea-rags-hooks}}}"
STATE="$STATE_DIR/drift-$HARNESS-$SID"
NOW="${TEA_RAGS_HOOK_NOW:-$(date +%s)}"

SEARCHES=0 READS=0 TOTAL=0 LAST_DENY=0
if [ -f "$STATE" ]; then
  read -r SEARCHES READS TOTAL LAST_DENY < "$STATE" 2>/dev/null
  case "$SEARCHES$READS$TOTAL$LAST_DENY" in *[!0-9]* | "") SEARCHES=0 READS=0 TOTAL=0 LAST_DENY=0 ;; esac
fi
save() { # <searches> <reads> <total> <last deny>; fails when the state is unwritable
  mkdir -p "$STATE_DIR" 2>/dev/null || return 1
  printf '%s %s %s %s\n' "$1" "$2" "$3" "$4" > "$STATE.$$" 2>/dev/null && mv -f "$STATE.$$" "$STATE" 2>/dev/null
}

case "$EVENT" in
  posttooluse | aftermcpexecution)
    TOOL=$(field '.tool_name')
    SERVER=$(field '.mcp_server_name')
    case "$TOOL|$SERVER" in
      mcp__*tea-rags*__* | *"|"*tea-rags*) ;;
      *) pass ;;
    esac
    # Cursor reports the call even when it failed; an error result resets nothing.
    FAILED=$(printf '%s' "$INPUT" | jq -r '(.result_json // "{}") | (if type == "string" then (fromjson? // {}) else . end) | .isError // false' 2>/dev/null)
    [ "$FAILED" = true ] && pass
    [ -f "$STATE" ] && save 0 0 0 "$LAST_DENY"
    pass
    ;;
  userpromptsubmit | beforesubmitprompt)
    # A new user prompt is a fresh routing decision: drift is a within-turn
    # phenomenon, so the counters reset and only the deny cooldown survives.
    [ -f "$STATE" ] && save 0 0 0 "$LAST_DENY"
    # Cursor's beforeSubmitPrompt takes {"continue":true}; the others take no output.
    [ "$HARNESS" = cursor ] && echo '{"continue":true}'
    exit 0
    ;;
  pretooluse) ;;
  *) allow ;;
esac

BIN="${TEA_RAGS_BIN:-}"
[ -n "$BIN" ] || BIN=$(command -v tea-rags 2>/dev/null)
if [ -z "$BIN" ]; then
  for CANDIDATE in "$HOME/.npm-global/bin/tea-rags" /opt/homebrew/bin/tea-rags /usr/local/bin/tea-rags; do
    [ -x "$CANDIDATE" ] && { BIN="$CANDIDATE"; break; }
  done
fi
CWD=$(field '.cwd // .workspace_roots[0]')
CWD="${CWD:-${CLAUDE_PROJECT_DIR:-${CURSOR_PROJECT_DIR:-}}}"
indexed_rel() { # <tea-rags project indexed args…> → relativePath of an indexed file, else empty
  [ -n "$BIN" ] || return 0
  "$BIN" project indexed "$@" --json 2>/dev/null | jq -r 'select(.indexed == true) | .relativePath // empty' 2>/dev/null
}

# Core routes these to the standard tools (bd tea-rags-mcp-nxg76): config, DSL, routes,
# initializers, migrations, specs / tests / fixtures, data files. A read of one or a
# search scoped to one is the routed path, never drift.
standard_zone() { # <text: a path, or a whole command>
  printf '%s' "$1" | grep -qE "(^|[/[:space:]'\"=])(config|spec|specs|test|tests|__tests__|fixtures|db|migrate|migrations|initializers|routes)(/|[[:space:]'\"]|$)|(_spec|_test|\.spec|\.test)\.[A-Za-z]+([[:space:]'\"]|$)|(^|/)routes\.[A-Za-z]+|\.(ya?ml|json|toml|ini|sql|rake|lock|env)([[:space:]'\"]|$)"
}
# A concept search done by text search: an alternation of words (`a|b`, `a\|b`, two -e
# patterns). A single literal — an identifier, constant, phrase — is the routed occurrence
# search and never counts; so does any -F / --fixed-strings search.
concept_shell_search() { # <command>
  printf '%s' "$1" | grep -qE '(^|[[:space:]])(-[A-Za-z]*F[A-Za-z]*|--fixed-strings)([[:space:]]|$)' && return 1
  printf '%s' "$1" | grep -qF '\|' && return 0
  printf '%s' "$1" | grep -qE "'[^']*[|][^']*'|\"[^\"]*[|][^\"]*\"" && return 0
  printf '%s' "$1" | grep -qE '(^|[[:space:]])-e[[:space:]].*[[:space:]]-e[[:space:]]'
}

rel_text() { # <text> → the text with "$CWD/" removed, so a zone word in the checkout path never counts
  if [ -n "$CWD" ]; then printf '%s' "${1//"$CWD"\//}"; else printf '%s' "$1"; fi
}

KIND=""
REL=""
case "$(field '.tool_name')" in
  Grep)
    PATTERN=$(field '.tool_input.pattern')
    SCOPE=$(printf '%s' "$INPUT" | jq -r '[.tool_input // {} | to_entries[] | select(.key != "pattern") | .value | strings] | join(" ")' 2>/dev/null)
    case "$PATTERN" in *"|"*) standard_zone "$(rel_text "$SCOPE")" || KIND=search ;; esac
    ;;
  Read)
    FILE=$(field '.tool_input.file_path // .tool_input.path // .tool_input.target_file')
    [ -n "$FILE" ] || allow
    case "$(printf '%s' "${FILE##*.}" | tr '[:upper:]' '[:lower:]')" in
      png | jpg | jpeg | gif | webp | bmp | ico | svg | pdf | zip | gz | tgz | tar | woff | woff2 | ttf | mp4 | mov | wav | mp3) allow ;;
    esac
    standard_zone "$(rel_text "$FILE")" && allow
    case "$FILE" in /*) ;; *) [ -n "$CWD" ] || allow; FILE="$CWD/$FILE" ;; esac
    REL=$(indexed_rel --path "$FILE")
    [ -n "$REL" ] && KIND=read
    ;;
  Bash | Shell | shell | exec_command)
    # tool_input.command: a string, or an argv array ([bash, -lc, <code>] → <code>).
    COMMAND=$(printf '%s' "$INPUT" | jq -r '
      .tool_input.command
      | if type == "array" then
          (map(tostring)) as $a
          | if ($a | length) >= 3 and ($a[0] | test("(^|/)(ba|z|da)?sh$")) and ($a[1] | test("^-[a-z]*c$"))
            then $a[2]
            else ($a | map(if test("^[A-Za-z0-9_@%+=:,./-]+$") then . else @sh end) | join(" ")) end
        elif type == "string" then . else empty end' 2>/dev/null)
    [ -n "$COMMAND" ] || allow
    W=$(field '.tool_input.workdir')
    case "$W" in "") ;; /*) CWD="$W" ;; *) CWD="$CWD/$W" ;; esac
    if [ -n "$CWD" ] && printf '%s' "$COMMAND" | grep -qE '(^|[;&|(`[:space:]])(cat|sed|head|tail|less|more)([[:space:]]|$)'; then
      REL=$(indexed_rel --command "$COMMAND" --cwd "$CWD")
    fi
    if [ -n "$REL" ]; then
      standard_zone "$REL" || KIND=read
    elif printf '%s' "$COMMAND" | grep -qE '(^|[;&(`]|\|\||\$\()[[:space:]]*(([A-Za-z_][A-Za-z0-9_]*=[^[:space:]]*|sudo|command|env)[[:space:]]+)*(grep|egrep|fgrep|rg|ag|ack|git[[:space:]]+grep)([[:space:]]|$)'; then
      concept_shell_search "$COMMAND" && ! standard_zone "$(rel_text "$COMMAND")" && KIND=search
    fi
    ;;
esac
[ -n "$KIND" ] || allow

if [ "$KIND" = search ]; then
  SEARCHES=$((SEARCHES + 1)) READS=0
else
  READS=$((READS + 1)) SEARCHES=0
fi
TOTAL=$((TOTAL + 1))

TRIGGER=""
if [ "$SEARCHES" -ge 3 ]; then
  TRIGGER=search
elif [ "$READS" -ge 3 ]; then
  TRIGGER=read
elif [ "$TOTAL" -ge 4 ]; then
  TRIGGER=mixed
fi
if [ -z "$TRIGGER" ] || [ $((NOW - LAST_DENY)) -lt 120 ]; then
  save "$SEARCHES" "$READS" "$TOTAL" "$LAST_DENY"
  allow
fi
save 0 0 0 "$NOW" || allow

TAIL="Counter reset — you may continue; this reminder fires at most once per 120 s."
case "$TRIGGER" in
  search) REASON="tea-rags: $SEARCHES concept searches by text alternation in a row, no tea-rags call. Behaviour/concept → semantic_search; a name + intent → hybrid_search(metaOnly: true); then find_symbol(symbol:) on the hit. $TAIL" ;;
  read) REASON="tea-rags: $READS reads of indexed code in a row, no tea-rags call. Read code with find_symbol(relativePath: \"${REL:-<file>}\") or ONE find_symbol(symbols: [<ids>]); flow → get_callees / get_callers. $TAIL" ;;
  *) REASON="tea-rags: $TOTAL text searches / code reads in a row, no tea-rags call. Behaviour → semantic_search; read code → find_symbol(relativePath:) or ONE find_symbol(symbols: [<ids>]); flow → get_callees / get_callers. $TAIL" ;;
esac

case "$HARNESS" in
  codex)
    echo "$REASON" >&2
    exit 2
    ;;
  cursor)
    jq -n --arg reason "$REASON" '{ permission: "deny", user_message: $reason, agent_message: $reason }' 2>/dev/null || allow
    ;;
  *)
    jq -n --arg reason "$REASON" '{
      hookSpecificOutput: {
        hookEventName: "PreToolUse",
        permissionDecision: "deny",
        permissionDecisionReason: $reason
      }
    }' 2>/dev/null
    ;;
esac
exit 0
