/**
 * The disk side of the Rust external signature table (bd s3i8m.7 T2): Cargo.lock
 * parsing, rust-src location, lazy dependency selection from the project's `use`
 * heads, the size cap and the extracted-table cache. Every source is injected —
 * the fixture `cargo-home/` and `sysroot/`, never the machine's own toolchain.
 */
import { mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import {
  cargoLockDirectDependencies,
  createRustExternalSignatureSources,
  locateRustLibrary,
  parseCargoLock,
  rustUseHeadsOf,
} from "../../../../src/core/adapters/rust-signatures/index.js";
import type { RustExternalSignatureTableData } from "../../../../src/core/contracts/index.js";

const FIXTURES = join(process.cwd(), "tests/fixtures/rust-external-signatures");
const CARGO_HOME = join(FIXTURES, "cargo-home");
const LIBRARY = join(FIXTURES, "sysroot/lib/rustlib/src/rust/library");
const PROJECT = join(FIXTURES, "project");

const LOCK_V3 = `# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "member"
version = "0.1.0"
dependencies = [
 "regex 1.10.2",
 "kvproto",
 "local-util",
]

[[package]]
name = "regex"
version = "1.10.2"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aa"

[[package]]
name = "regex"
version = "0.2.11"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "bb"

[[package]]
name = "kvproto"
version = "0.0.2"
source = "git+https://github.com/pingcap/kvproto.git?branch=master#623e58e1c2b3d4f5"

[[package]]
name = "local-util"
version = "0.0.1"
`;

const LOCK_V1 = `[[package]]
name = "member"
version = "0.1.0"
dependencies = [
 "log 0.4.8 (registry+https://github.com/rust-lang/crates.io-index)",
]

[[package]]
name = "log"
version = "0.4.8"
source = "registry+https://github.com/rust-lang/crates.io-index"
`;

describe("parseCargoLock", () => {
  it("reads registry, git and path packages of a v3 lockfile", () => {
    const packages = parseCargoLock(LOCK_V3);
    expect(packages.map((p) => [p.name, p.version, p.source.kind])).toEqual([
      ["member", "0.1.0", "path"],
      ["regex", "1.10.2", "registry"],
      ["regex", "0.2.11", "registry"],
      ["kvproto", "0.0.2", "git"],
      ["local-util", "0.0.1", "path"],
    ]);
    expect(packages[3]?.source).toEqual({ kind: "git", repository: "kvproto", rev: "623e58e1c2b3d4f5" });
    expect(packages[0]?.dependencies).toEqual(["regex 1.10.2", "kvproto", "local-util"]);
  });

  it("reads a v4 lockfile with a query-string git source", () => {
    const packages = parseCargoLock(
      `version = 4\n\n[[package]]\nname = "selectors"\nversion = "0.41.0"\nsource = "git+https://github.com/servo/stylo?rev=6091d92b1d6f#6091d92b1d6f06938572"\n`,
    );
    expect(packages).toEqual([
      {
        name: "selectors",
        version: "0.41.0",
        source: { kind: "git", repository: "stylo", rev: "6091d92b1d6f06938572" },
        dependencies: [],
      },
    ]);
  });

  it("treats a sparse registry source as a registry", () => {
    const [pkg] = parseCargoLock(
      `[[package]]\nname = "a"\nversion = "1.0.0"\nsource = "sparse+https://index.crates.io/"\n`,
    );
    expect(pkg?.source.kind).toBe("registry");
  });
});

describe("cargoLockDirectDependencies", () => {
  it("resolves the members' dependency entries to exact packages and skips path members", () => {
    const direct = cargoLockDirectDependencies(parseCargoLock(LOCK_V3));
    expect(direct.map((p) => `${p.name} ${p.version}`)).toEqual(["kvproto 0.0.2", "regex 1.10.2"]);
  });

  it("resolves a v1 `name version (source)` entry", () => {
    const direct = cargoLockDirectDependencies(parseCargoLock(LOCK_V1));
    expect(direct.map((p) => `${p.name} ${p.version}`)).toEqual(["log 0.4.8"]);
  });
});

describe("rustUseHeadsOf", () => {
  it("collects use / pub use / extern crate heads and drops crate-relative ones", () => {
    const source = [
      "use serde_json::Value;",
      "pub use ::tokio::sync;",
      "pub(crate) use regex::{Regex, RegexBuilder};",
      "extern crate libc;",
      "use crate::local::Thing;",
      "use self::inner::X;",
      "use super::Y;",
      "    use bytes::Bytes;",
    ].join("\n");
    expect([...rustUseHeadsOf(source)].sort()).toEqual(["bytes", "libc", "regex", "serde_json", "tokio"]);
  });
});

describe("locateRustLibrary", () => {
  it("prefers RUST_SRC_PATH and identifies it by its file listing when no library Cargo.lock exists", () => {
    const runRustc = vi.fn(() => undefined);
    const found = locateRustLibrary({ env: { RUST_SRC_PATH: LIBRARY }, runRustc });
    expect(found?.libraryDir).toBe(LIBRARY);
    expect(found?.toolchainId).toMatch(/^src-[0-9a-f]{16}$/);
    expect(runRustc).not.toHaveBeenCalled();
    expect(locateRustLibrary({ env: { RUST_SRC_PATH: LIBRARY }, runRustc })?.toolchainId).toBe(found?.toolchainId);
  });

  it("identifies a rustc sysroot by its commit hash", () => {
    const sysroot = join(FIXTURES, "sysroot");
    const runRustc = vi.fn((args: readonly string[]) =>
      args[0] === "--print"
        ? `${sysroot}\n`
        : "rustc 1.88.0 (6b00bc388 2025-06-23)\ncommit-hash: 6b00bc3880198600130e1cf62b8f8a93494488cc\n",
    );
    expect(locateRustLibrary({ env: {}, runRustc })).toEqual({
      libraryDir: LIBRARY,
      toolchainId: "6b00bc3880198600130e1cf62b8f8a93494488cc",
    });
  });

  it("answers nothing when rustc is missing or its sysroot has no rust-src", () => {
    expect(locateRustLibrary({ env: {}, runRustc: () => undefined })).toBeUndefined();
    expect(locateRustLibrary({ env: {}, runRustc: () => "/nonexistent-sysroot\n" })).toBeUndefined();
    expect(
      locateRustLibrary({ env: { RUST_SRC_PATH: "/nonexistent-src" }, runRustc: () => undefined }),
    ).toBeUndefined();
  });
});

describe("createRustExternalSignatureSources", () => {
  let cacheDir: string;
  beforeEach(() => {
    cacheDir = mkdtempSync(join(tmpdir(), "rust-signatures-"));
  });
  afterEach(() => {
    rmSync(cacheDir, { recursive: true, force: true });
  });

  const sourcesWith = (overrides: { sizeCapBytes?: number; env?: Record<string, string> } = {}) =>
    createRustExternalSignatureSources({
      cacheDir,
      env: { CARGO_HOME, RUST_SRC_PATH: LIBRARY, ...overrides.env },
      runRustc: () => undefined,
      ...(overrides.sizeCapBytes === undefined ? {} : { sizeCapBytes: overrides.sizeCapBytes }),
    });

  it("selects only the dependencies a project use head names, registry and git, and lists the missing", () => {
    const found = sourcesWith().locate(PROJECT);
    expect(found.dependencies.map((set) => set.cacheKey)).toEqual(["crates/demo-0.1.0", "crates/gitdep-git-1234567"]);
    expect(found.missingCrates).toEqual(["absent-dep 9.9.9"]);
    expect(found.lockDigest).toMatch(/^[0-9a-f]{64}$/);
    expect(found.std?.cacheKey).toMatch(/^std\/src-[0-9a-f]{16}$/);
  });

  it("reads a dependency's sources relative to its src/ directory, git crates from their checkout subdirectory", () => {
    const [demo, gitdep] = sourcesWith().locate(PROJECT).dependencies;
    expect(demo?.readSources()?.map((file) => [file.crate, file.relPath])).toEqual([
      ["demo", "client.rs"],
      ["demo", "lib.rs"],
    ]);
    expect(gitdep?.readSources()?.map((file) => [file.crate, file.relPath])).toEqual([["gitdep", "lib.rs"]]);
  });

  it("reads std, core and alloc as one set", () => {
    const crates = new Set(
      sourcesWith()
        .locate(PROJECT)
        .std?.readSources()
        ?.map((file) => file.crate),
    );
    expect([...crates].sort()).toEqual(["alloc", "core", "std"]);
  });

  it("skips a dependency over the size cap", () => {
    const sources = sourcesWith({ sizeCapBytes: 10 });
    const [demo] = sources.locate(PROJECT).dependencies;
    expect(demo?.readSources()).toBeUndefined();
    expect(sources.sizeCapBytes).toBe(10);
  });

  it("degrades to no std and no dependencies without rust-src, lock or CARGO_HOME", () => {
    const sources = createRustExternalSignatureSources({ cacheDir, env: {}, runRustc: () => undefined });
    const found = sources.locate(join(FIXTURES, "sysroot"));
    expect(found).toEqual({ std: undefined, dependencies: [], lockDigest: undefined, missingCrates: [] });
  });

  it("round-trips a table through the cache, misses on an absent key and drops a corrupt file", () => {
    const sources = sourcesWith();
    const data: RustExternalSignatureTableData = {
      crates: ["demo"],
      paths: { "demo::Client": "demo::Client" },
      types: {},
      aliases: {},
    };
    expect(sources.readCached("crates/demo-0.1.0-x1")).toBeUndefined();
    sources.writeCached("crates/demo-0.1.0-x1", data);
    expect(sources.readCached("crates/demo-0.1.0-x1")).toEqual(data);
    expect(readdirSync(join(cacheDir, "crates"))).toEqual(["demo-0.1.0-x1.json"]);

    mkdirSync(join(cacheDir, "std"), { recursive: true });
    writeFileSync(join(cacheDir, "std/abc-x1.json"), "{ not json");
    expect(sources.readCached("std/abc-x1")).toBeUndefined();
    expect(readdirSync(join(cacheDir, "std"))).toEqual([]);

    writeFileSync(join(cacheDir, "std/shape-x1.json"), JSON.stringify({ crates: "std" }));
    expect(sources.readCached("std/shape-x1")).toBeUndefined();
    expect(readdirSync(join(cacheDir, "std"))).toEqual([]);
  });
});
