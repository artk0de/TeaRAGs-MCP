import { mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { afterAll, beforeAll, describe, expect, it } from "vitest";

import { renderAgentContextModule, writeAgentContextModule } from "../../../scripts/gen-agent-context.js";

const ROOT = resolve(__dirname, "../../..");
const MODULE_PATH = resolve(ROOT, "src/mcp/resources/generated/agent-context.ts");
const RULES_DIR = resolve(ROOT, "plugins/tea-rags/rules");

interface AgentContextModule {
  AGENT_CONTEXT_CORE: string;
  AGENT_CONTEXT_GUIDES: Readonly<Record<string, string>>;
}

/**
 * Render properties of the agent-context module. The committed copy is not
 * compared: release regenerates it (`npm run gen:plugins`) and `prebuild`
 * regenerates it before every build, so a PR editing the rules alone is valid.
 */
describe("renderAgentContextModule", () => {
  let scratch: string;
  let rendered: string;
  let loaded: AgentContextModule;

  beforeAll(async () => {
    scratch = mkdtempSync(join(tmpdir(), "agent-context-"));
    rendered = await renderAgentContextModule(RULES_DIR, MODULE_PATH);
    const modulePath = join(scratch, "agent-context.ts");
    await writeAgentContextModule({ rulesDir: RULES_DIR, modulePath });
    loaded = (await import(pathToFileURL(modulePath).href)) as AgentContextModule;
  });

  afterAll(() => {
    rmSync(scratch, { recursive: true, force: true });
  });

  it("renders byte-identically twice", async () => {
    expect(await renderAgentContextModule(RULES_DIR, MODULE_PATH)).toBe(rendered);
  });

  it("carries rules/core.md verbatim as the core", () => {
    expect(loaded.AGENT_CONTEXT_CORE).toBe(readFileSync(join(RULES_DIR, "core.md"), "utf8"));
  });

  it("carries every guide verbatim, keyed by file name", () => {
    const guidesDir = join(RULES_DIR, "guides");
    const guides = readdirSync(guidesDir)
      .filter((file) => file.endsWith(".md"))
      .sort();

    expect(Object.keys(loaded.AGENT_CONTEXT_GUIDES)).toEqual(guides.map((file) => basename(file, ".md")));
    for (const file of guides) {
      expect(loaded.AGENT_CONTEXT_GUIDES[basename(file, ".md")], file).toBe(
        readFileSync(join(guidesDir, file), "utf8"),
      );
    }
  });

  it("marks the module as generated", () => {
    expect(rendered.startsWith("// GENERATED by `npm run gen:agent-context`")).toBe(true);
  });
});
