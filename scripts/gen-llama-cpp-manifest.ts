/**
 * Regenerate `src/core/adapters/llama-server/install/llama-cpp-manifest.generated.ts`
 * from a llama.cpp GitHub release: every `llama-<build>-bin-*` and `cudart-*`
 * asset with the sha256 GitHub publishes in the asset's `digest` field.
 *
 * Run by hand only — tests read the committed output, never the network.
 *
 *   npx tsx scripts/gen-llama-cpp-manifest.ts            # re-pin the current build
 *   npx tsx scripts/gen-llama-cpp-manifest.ts b12345     # bump to another build
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { LLAMA_CPP_BUILD } from "../src/core/adapters/llama-server/install/llama-cpp-manifest.generated.js";

interface GitHubReleaseAsset {
  name: string;
  digest?: string | null;
}

const OUTPUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/core/adapters/llama-server/install/llama-cpp-manifest.generated.ts",
);

function isBinaryAsset(name: string, build: string): boolean {
  return name.startsWith(`llama-${build}-bin-`) || name.startsWith("cudart-");
}

async function main(): Promise<void> {
  const build = process.argv[2] ?? LLAMA_CPP_BUILD;
  const response = await fetch(`https://api.github.com/repos/ggml-org/llama.cpp/releases/tags/${build}`, {
    headers: { accept: "application/vnd.github+json" },
  });
  if (!response.ok) throw new Error(`GitHub release ${build}: HTTP ${response.status}`);
  const release = (await response.json()) as { assets: GitHubReleaseAsset[] };

  const lines: string[] = [];
  for (const asset of [...release.assets].sort((a, b) => a.name.localeCompare(b.name))) {
    if (!isBinaryAsset(asset.name, build)) continue;
    const sha256 = asset.digest?.startsWith("sha256:") ? asset.digest.slice("sha256:".length) : undefined;
    if (sha256 === undefined) throw new Error(`Asset ${asset.name} has no sha256 digest`);
    lines.push(`  "${asset.name}": "${sha256}",`);
  }

  writeFileSync(
    OUTPUT,
    [
      "// GENERATED by scripts/gen-llama-cpp-manifest.ts — do not edit by hand.",
      "",
      "/** The pinned llama.cpp release whose binaries `tea-rags llama-server install` downloads. */",
      `export const LLAMA_CPP_BUILD = "${build}";`,
      "",
      "/** Release asset name → sha256 (lowercase hex), from the GitHub asset `digest`. */",
      "export const LLAMA_CPP_ASSET_SHA256: Readonly<Record<string, string>> = {",
      ...lines,
      "};",
      "",
    ].join("\n"),
  );
  process.stdout.write(`${OUTPUT}: ${lines.length} assets for ${build}\n`);
}

await main();
