import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { format, resolveConfig } from "prettier";

const here = dirname(fileURLToPath(import.meta.url));

export interface AgentContextPaths {
  rulesDir: string;
  modulePath: string;
}

export const DEFAULT_PATHS: AgentContextPaths = {
  rulesDir: resolve(here, "../plugins/tea-rags/rules"),
  modulePath: resolve(here, "../src/mcp/resources/generated/agent-context.ts"),
};

const HEADER = "// GENERATED by `npm run gen:agent-context` from plugins/tea-rags/rules — DO NOT EDIT.";

function readCore(rulesDir: string): string {
  const corePath = resolve(rulesDir, "core.md");
  return existsSync(corePath) ? readFileSync(corePath, "utf8") : "";
}

/** Guide basename (no `.md`) → markdown, sorted by file name. */
function readGuides(rulesDir: string): [string, string][] {
  const guidesDir = resolve(rulesDir, "guides");
  if (!existsSync(guidesDir)) return [];
  return readdirSync(guidesDir)
    .filter((file) => file.endsWith(".md"))
    .sort()
    .map((file) => [basename(file, ".md"), readFileSync(resolve(guidesDir, file), "utf8")]);
}

/**
 * The `agent-context.ts` module for `rulesDir` — `core.md` and `guides/*.md` as
 * string constants, Prettier-formatted with the project config so the committed
 * file is byte-identical to what `lint-staged` would write and the drift guard
 * stays stable. Absent `core.md` → empty core; absent `guides/` → no guides.
 */
export async function renderAgentContextModule(
  rulesDir: string = DEFAULT_PATHS.rulesDir,
  modulePath: string = DEFAULT_PATHS.modulePath,
): Promise<string> {
  const entries = readGuides(rulesDir)
    .map(([key, markdown]) => `  ${JSON.stringify(key)}: ${JSON.stringify(markdown)},`)
    .join("\n");
  const source = `${HEADER}

export const AGENT_CONTEXT_CORE = ${JSON.stringify(readCore(rulesDir))} as string;

export const AGENT_CONTEXT_GUIDES: Readonly<Record<string, string>> = {
${entries}
};
`;
  const config = await resolveConfig(modulePath);
  return format(source, { ...config, filepath: modulePath, parser: "typescript" });
}

export async function writeAgentContextModule({ rulesDir, modulePath }: AgentContextPaths): Promise<void> {
  writeFileSync(modulePath, await renderAgentContextModule(rulesDir, modulePath), "utf8");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeAgentContextModule(DEFAULT_PATHS);
  console.log("✓ src/mcp/resources/generated/agent-context.ts regenerated from plugin rules.");
}
